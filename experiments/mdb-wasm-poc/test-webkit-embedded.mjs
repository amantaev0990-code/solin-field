// Real mobile-WebKit end-to-end test: main Field page stays visible while
// an off-screen same-origin Blazor frame generates and returns its MDB bytes.
import { webkit } from 'playwright';
import fs from 'node:fs';
import vm from 'node:vm';

const meta=JSON.parse(fs.readFileSync('data-meta.json','utf8'));
const manifest=JSON.parse(fs.readFileSync('data-manifest.json','utf8'));
const quarters=Object.assign({},...manifest.quarterChunks.map(p=>
  JSON.parse(fs.readFileSync(p,'utf8'))));
const org=meta.lesnichestvo[0];
const stands=Object.values(quarters).flatMap(q=>q.compartments||[]);
if(stands.length!==471)throw Error('Expected 471 stand records');
stands[225].PRkol='0,6';
const forest={id:org.POS+'::'+org.LESN,org,quarters,source:meta.source,extraTables:{},
              updatedAt:new Date().toISOString(),history:[]};

const base='/tmp/mdw-www/solin-field';
fs.mkdirSync(base,{recursive:true});
fs.writeFileSync(base+'/export-harness.html',
  '<!doctype html><html lang="ru"><meta charset="utf-8">'+
  '<title>SOLI-N Field — integration test</title>'+
  '<div id="menuScreen"><div class="workspace">'+
  '<button id="solin-mdb-export" class="menuRow">Экспорт</button></div></div>'+
  '<script>window.SolinWorkspace={ready:Promise.resolve(),activeId:"213::2",persist:async()=>{}};'+
  'window.SolinMDBBridge={snapshot:()=>({format:"SOLIN-MDB-Bridge-v1",'+
  'identity:{POS:213,LESN:2,GodT:2026},tables:Object.fromEntries('+ 
  'Array.from({length:18},(_,n)=>["Table"+n,[]]))})};</script>'+
  '<script src="solin-mdb-wasm-entry.js"></script></html>');

const browser=await webkit.launch({headless:true});
let page;
try {
  page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:3,acceptDownloads:true});
  page.on('console',message=>{
    if(message.type()==='error')console.error('WEBKIT: '+message.text());
  });
  const url='http://127.0.0.1:8765/solin-field/export-harness.html';
  await page.goto(url,{waitUntil:'domcontentloaded',timeout:60000});
  await page.evaluate(async forest=>{
    await new Promise((resolve,reject)=>{
      const request=indexedDB.open('SOLIN_WORKSPACES_V1',2);
      request.onupgradeneeded=()=>{
        if(!request.result.objectStoreNames.contains('forests'))
          request.result.createObjectStore('forests',{keyPath:'id'});
      };
      request.onerror=()=>reject(request.error);
      request.onsuccess=()=>{
        const db=request.result;
        const transaction=db.transaction('forests','readwrite');
        transaction.objectStore('forests').put(forest);
        transaction.oncomplete=()=>{
          localStorage.setItem('solin_active_forest_v1',forest.id);
          db.close();resolve();
        };
        transaction.onerror=()=>reject(transaction.error);
      };
    });
  },forest);

  const downloads=[];
  page.on('download',download=>downloads.push(download));
  const button=page.locator('#solin-mdb-export');
  await button.click();
  await button.filter({hasText:'MDB готов'}).waitFor({timeout:180000});
  // Some Safari contexts suppress the async click. A second trusted tap
  // on the SAME button saves already generated bytes without rerunning WASM.
  if(!downloads.length) {
    const received=page.waitForEvent('download',{timeout:60000});
    await button.click();
    await received;
  }
  const download=downloads[0];
  if(!download)throw Error('No MDB offered for download');
  if(download.suggestedFilename()!=='Transf_213_2_2026.mdb')
    throw Error('Incorrect MDB filename: '+download.suggestedFilename());
  if(page.url()!==url)throw Error('Export navigated out of SOLI-N Field');
  await page.waitForFunction(()=>document.querySelectorAll('iframe').length===0);
  if(await page.getByText('Отдельный эксперимент SOLI-N Field').count())
    throw Error('Separate experiment UI is exposed');

  const bytes=fs.readFileSync(await download.path());
  if(bytes.toString('latin1',4,19)!=='Standard Jet DB')
    throw Error('Downloaded file is not Jet MDB');
  const sandbox={console,Buffer,Uint8Array,ArrayBuffer,TextEncoder,TextDecoder,Date};
  vm.createContext(sandbox);
  vm.runInContext(fs.readFileSync('vendor/mdb-reader.bundle.js','utf8'),sandbox,
                  {timeout:30000,filename:'mdb-reader.bundle.js'});
  const reader=new sandbox.SolinMDB.Reader(sandbox.SolinMDB.Buffer.from(bytes));
  const names=reader.getTableNames({normalTables:true,systemTables:false,linkedTables:false});
  let count=0;
  for(const name of names)count+=reader.getTable(name).getData().length;
  if(names.length!==18||count!==1243)
    throw Error('Wrong MDB contents: '+names.length+' tables, '+count+' rows');
  const readBack=Number(reader.getTable('Выдел').getData()[225].PRkol);
  if(Math.abs(readBack-0.6)>0.000001)throw Error('Original edited fraction lost: '+readBack);
  console.log('WEBKIT_INPLACE_MDB_OK: Field never navigated, 18 tables, 1243 rows, fraction 0.6, one Export button');
}catch(error){
  console.error('WEBKIT_INPLACE_MDB_FAILED: '+error.stack);
  await page?.screenshot({path:'/tmp/solin-inplace-export-failed.png'}).catch(()=>{});
  process.exitCode=1;
}finally{
  await browser.close();
}
