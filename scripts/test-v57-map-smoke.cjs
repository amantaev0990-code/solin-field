const fs=require('node:fs');
const assert=require('node:assert/strict');
const vm=require('node:vm');
const html=fs.readFileSync('index.html','utf8');
const map=fs.readFileSync('map.js','utf8');
const imagery=fs.readFileSync('solin-offline-imagery.js','utf8');
const css=fs.readFileSync('map.css','utf8');
const sw=fs.readFileSync('sw.js','utf8');
for(const [name,script] of [['map.js',map],['solin-offline-imagery.js',imagery],['sw.js',sw]])
 assert.doesNotThrow(()=>new vm.Script(script,{filename:name}),name+' must parse');
assert.doesNotMatch(html,/id="offlineImportBtn"/,'duplicate MBTiles toolbar must be gone');
assert.match(map,/\.zip,\.mbtiles/,'MBTiles should remain in the universal file picker');
assert.match(map,/position:'bottomleft'/,'tools must be at bottom');
assert.match(css,/field-map-tools\[open\]/,'tools must expand vertically');
assert.match(imagery,/function batchedTileRead/,'offline reads must be batched');
assert.match(imagery,/data-use-map/,'saved maps must be reopenable');
assert.match(imagery,/data-remove-map/,'saved maps must be removable');
assert.doesNotMatch(map,/https:\/\/\{s\}\.google\.com/,'do not use an unapproved Google tile endpoint');
assert.match(map,/tiles\.maps\.eox\.at/,'license-compliant online source');
assert.match(sw,/20261112-v57-map/,'PWA assets must be invalidated');
const fakeWindow={};
const fakeDocument={readyState:'loading',addEventListener(){}};
vm.runInNewContext(imagery,{window:fakeWindow,document:fakeDocument,navigator:{},console});
const offline=fakeWindow.SolinOfflineImagery;
assert.ok(offline&&offline.plan,'offline service exports a download planner');
const area=offline.plan([76.8,42.7,76.9,42.8],12);
assert.ok(area.length>0&&area.length<5000,'bounded regional download');
assert.throws(()=>offline.plan([76.8,42.7,76.9,42.8],15),/Масштаб/,'prevent unavailable detail');
assert.throws(()=>offline.plan([-120,-60,120,60],14),/слишком большая/,'prevent unbounded downloads');
console.log('V57_MAP_SMOKE_OK: toolbar, fullscreen tools, offline catalog, tiles, satellite, bounded download');
