#!/usr/bin/env python3
"""Build the mobile control bundle from physically decoded, read-only SOLI-N sources.

Usage: python scripts/build-control-data.py /path/to/SOLI-N
No MDB, source rows, or working card data are changed or bundled.
"""
import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

source = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
query_path = source / 'SOLIN_SOLIM_MSYSQUERIES_DECODED_2026-10-10.json.gz'
table_path = source / 'SOLIN_SOLIM_ALL_USER_TABLE_ROWS_2026-10-11.json.gz'
queries = json.loads(gzip.decompress(query_path.read_bytes()))['queries']
tables = json.loads(gzip.decompress(table_path.read_bytes()))['tables']


def compact(name):
    rows = sorted(queries[name], key=lambda r: (r['Attribute'], r['Order']))
    return {
        'sources': [r['Name1'] for r in rows if r['Attribute'] == 5],
        'columns': [{'expression': r['Expression'], 'alias': r['Name1']}
                    for r in rows if r['Attribute'] == 6 and not (r['Flag'] or 0) & 2],
        'joins': [{'left': r['Name1'], 'right': r['Name2'], 'kind': r['Flag'],
                   'expression': r['Expression']} for r in rows if r['Attribute'] == 7],
        'where': next((r['Expression'] for r in rows if r['Attribute'] == 8), None),
        'group': [r['Expression'] for r in rows if r['Attribute'] == 9],
        'having': next((r['Expression'] for r in rows if r['Attribute'] == 10), None),
    }


catalog = []
plans = {}
for row in tables['Контроли']:
    code = re.sub(r'\s+', '', row['Kosh'])
    record = {**row, 'code': code, 'supported': False}
    if code in queries:
        plan = compact(code)
        gates = []
        for name in plan['sources']:
            if name in [code + '_2', code + '_3'] and name in queries:
                gate = compact(name)
                if all(s in ['Контроли', 'ВыделВыб', 'KUch'] for s in gate['sources']):
                    gates.append(name)
        supported = bool(plan['sources']) and not plan['group'] and not plan['having']
        supported = supported and all(
            s == 'ВыделВыб' or re.fullmatch(r'Макет\d+', s)
            or s.startswith('S') and (s in tables or s == 'SDP_Tip') or s in gates
            for s in plan['sources'])
        # Only direct predicates are enabled. Stateful staging, cross-controls,
        # temporary tables and VBA remain explicit gaps, never stale snapshots.
        if supported:
            plans[code] = plan
            for name in gates:
                plans[name] = compact(name)
            record['supported'] = True
        record['sources'] = plan['sources']
    catalog.append(record)

bundle = {
    'version': 1,
    'source': {
        'mdb': 'Solim.mdb',
        'sha256': 'f49dbcc449294e89632bbc6d6935dc2dcda8fa1732cd9b1f8e9378ca4bc42dcf',
        'queryArchiveSha256': hashlib.sha256(query_path.read_bytes()).hexdigest(),
        'tableArchiveSha256': hashlib.sha256(table_path.read_bytes()).hexdigest(),
        'nativeButtonParity': False,
        'scope': 'Direct saved predicates on current mobile data; no VBA preparation',
    },
    'catalog': catalog,
    'queries': plans,
}
(root / 'solin-control-data.js').write_text(
    '/* Generated by scripts/build-control-data.py; keep raw Kosh and NULLs. */\n'
    + 'window.SOLIN_CONTROL_DATA=' + json.dumps(bundle, ensure_ascii=False, separators=(',', ':')) + ';\n',
    encoding='utf-8')
print(f'{len(catalog)} catalogue entries; {sum(r["supported"] for r in catalog)} direct predicates; {len(plans)} query definitions')
